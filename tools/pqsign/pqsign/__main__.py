"""
pqsign command line.

  python3 -m pqsign keygen   --out keys/
  python3 -m pqsign sign     --keys keys/ --type bl31 --version 3 \
                             --load 0x0e060000 --entry 0x0e060000 \
                             --pq mldsa87 --in bl31.bin --out bl31.pqb
  python3 -m pqsign inspect  bl31.pqb
  python3 -m pqsign anchor   --keys keys/ --pq mldsa87 --json ta.json --c-header pqb_rotpk.h
  python3 -m pqsign golden   --out golden.json bl2.pqb bl31.pqb ...
  python3 -m pqsign verify-quote --quote q.bin --nonce <hex> --golden golden.json \
                             [--alias alias.pub]
  python3 -m pqsign lms-status --keys keys/
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys

from . import attest, image, keys

PQ = {"mldsa87": image.PQ_MLDSA87, "lms": image.PQ_LMS}


def _int(s: str) -> int:
    return int(s, 0)


def cmd_keygen(a) -> int:
    keys.generate(a.out, lms_type=0x06 if a.lms_h10 else 0x05)
    print(f"keys written to {a.out}/ (demo keys: unencrypted, keep them off git)")
    return 0


def cmd_sign(a) -> int:
    ks = keys.KeySet(a.keys)
    with open(a.input, "rb") as f:
        payload = f.read()
    img = image.build(payload, image.IMG_TYPES[a.type], a.version, a.load, a.entry,
                      ks, PQ[a.pq])
    out = image.to_trailer(img) if a.trailer else img
    with open(a.output, "wb") as f:
        f.write(out)
    form = "trailer" if a.trailer else "PQB1"
    print(f"{a.output}: {len(out)} bytes ({form}), measurement "
          f"{image.measurement(img).hex()[:32]}...")
    return 0


def cmd_inspect(a) -> int:
    with open(a.image, "rb") as f:
        img = f.read()
    p = image.split(img)
    h = p["hdr"]
    names = {v: k for k, v in image.IMG_TYPES.items()}
    print(f"type            : {names.get(h.image_type, h.image_type)}")
    print(f"pq algorithm    : {'ML-DSA-87' if h.pq_alg == 1 else 'LMS' if h.pq_alg == 2 else h.pq_alg}")
    print(f"security version: {h.security_version}")
    print(f"load / entry    : {h.load_addr:#x} / {h.entry_point:#x}")
    print(f"payload         : {h.payload_size} bytes, digest "
          f"{'OK' if hashlib.sha384(p['payload']).digest() == h.payload_digest else 'MISMATCH'}")
    print(f"key/sig sizes   : classic {h.classic_pk_len}/{h.classic_sig_len}, "
          f"pq {h.pq_pk_len}/{h.pq_sig_len}")
    print(f"key hash        : {hashlib.sha384(p['classic_pk'] + p['pq_pk']).hexdigest()}")
    print(f"measurement     : {image.measurement(img).hex()}")
    print(f"trailing bytes  : {p['trailing']}")
    return 0


def cmd_anchor(a) -> int:
    ks = keys.KeySet(a.keys)
    kh = ks.key_hash(PQ[a.pq])
    allowed = 1 << PQ[a.pq]
    if a.json:
        with open(a.json, "w") as f:
            json.dump({"key_hash": kh.hex(), "allowed_pq_algs": allowed}, f, indent=2)
    if a.c_header:
        body = ", ".join(f"0x{b:02x}" for b in kh)
        with open(a.c_header, "w") as f:
            f.write("/* Generated by pqsign anchor - SHA-384(classic_pk || pq_pk) */\n"
                    "#ifndef PQB_ROTPK_H\n#define PQB_ROTPK_H\n"
                    f"#define PQB_ROTPK_HASH {{ {body} }}\n"
                    f"#define PQB_ALLOWED_PQ_ALGS 0x{allowed:x}u\n#endif\n")
    print(kh.hex())
    return 0


def cmd_golden(a) -> int:
    out = {}
    for path in a.images:
        with open(path, "rb") as f:
            img = f.read()
        out[str(image.Header.unpack(img).image_type)] = image.measurement(img).hex()
    with open(a.out, "w") as f:
        json.dump(out, f, indent=2)
    print(f"{len(out)} golden measurements -> {a.out}")
    return 0


def cmd_verify_quote(a) -> int:
    with open(a.quote, "rb") as f:
        q = f.read()
    with open(a.golden) as f:
        golden = {int(k): bytes.fromhex(v) for k, v in json.load(f).items()}
    alias = None
    if a.alias:
        with open(a.alias, "rb") as f:
            alias = f.read()
    res = attest.verify(q, bytes.fromhex(a.nonce), golden, alias)
    if res.ok:
        print("ATTESTATION OK: device booted only known-good images")
        return 0
    print("ATTESTATION FAILED:")
    for r in res.reasons:
        print(f"  - {r}")
    return 1


def cmd_lms_status(a) -> int:
    ks = keys.KeySet(a.keys)
    if not ks.lms:
        print("no LMS key")
        return 1
    k = ks.lms.key
    print(f"LMS h={k.h}: {k.remaining()} of {1 << k.h} one-time signatures left")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="pqsign")
    sp = ap.add_subparsers(dest="cmd", required=True)

    p = sp.add_parser("keygen"); p.add_argument("--out", required=True)
    p.add_argument("--lms-h10", action="store_true", help="1024-leaf LMS tree (slower keygen)")
    p.set_defaults(fn=cmd_keygen)

    p = sp.add_parser("sign")
    p.add_argument("--keys", required=True)
    p.add_argument("--type", required=True, choices=image.IMG_TYPES)
    p.add_argument("--version", type=int, default=0)
    p.add_argument("--load", type=_int, default=0)
    p.add_argument("--entry", type=_int, default=0)
    p.add_argument("--pq", choices=PQ, default="mldsa87")
    p.add_argument("--in", dest="input", required=True)
    p.add_argument("--out", dest="output", required=True)
    p.add_argument("--trailer", action="store_true",
                   help="emit payload||sigblob||PQBT||len (for TF-A FIP images)")
    p.set_defaults(fn=cmd_sign)

    p = sp.add_parser("inspect"); p.add_argument("image"); p.set_defaults(fn=cmd_inspect)

    p = sp.add_parser("anchor")
    p.add_argument("--keys", required=True)
    p.add_argument("--pq", choices=PQ, default="mldsa87")
    p.add_argument("--json"); p.add_argument("--c-header")
    p.set_defaults(fn=cmd_anchor)

    p = sp.add_parser("golden"); p.add_argument("--out", required=True)
    p.add_argument("images", nargs="+"); p.set_defaults(fn=cmd_golden)

    p = sp.add_parser("verify-quote")
    p.add_argument("--quote", required=True); p.add_argument("--nonce", required=True)
    p.add_argument("--golden", required=True); p.add_argument("--alias")
    p.set_defaults(fn=cmd_verify_quote)

    p = sp.add_parser("lms-status"); p.add_argument("--keys", required=True)
    p.set_defaults(fn=cmd_lms_status)

    a = ap.parse_args(argv)
    return a.fn(a)


if __name__ == "__main__":
    sys.exit(main())
